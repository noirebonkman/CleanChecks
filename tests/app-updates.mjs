import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { build } from 'esbuild';
mkdirSync('.test-work', { recursive: true });
await build({entryPoints:['src/app-updates.ts'],outfile:'.test-work/app-updates-test.mjs',bundle:true,platform:'node',format:'esm'});
const {publishAppUpdate,subscribeAppUpdates,watchForAppUpdates}=await import('../.test-work/app-updates-test.mjs');
let applied=0, received;
const first=async()=>{applied++;};
publishAppUpdate(first);
assert.equal(applied,0);
const unsubscribe=subscribeAppUpdates(action=>{received=action;});
assert.equal(received,first,'Update delivered before login must be replayed after app mounting');
assert.equal(applied,0,'Updates must wait for explicit save-and-open action');
await received();assert.equal(applied,1);
unsubscribe();
const second=async()=>{applied+=10;};
publishAppUpdate(second);
assert.equal(received,first,'Unmounted components must not receive updates');
let next;const off=subscribeAppUpdates(action=>{next=action;});assert.equal(next,second);off();

const events=new EventTarget(),doc=Object.assign(new EventTarget(),{visibilityState:'visible'});
let clock=0,online=true,checks=0;
const stop=watchForAppUpdates({update:async()=>{checks++;}}, {window:events,document:doc,online:()=>online,now:()=>clock});
events.dispatchEvent(new Event('online'));assert.equal(checks,0);
clock=300001;doc.dispatchEvent(new Event('visibilitychange'));assert.equal(checks,1);
doc.dispatchEvent(new Event('visibilitychange'));assert.equal(checks,1);
clock=600002;online=false;events.dispatchEvent(new Event('online'));assert.equal(checks,1);
online=true;doc.visibilityState='hidden';events.dispatchEvent(new Event('online'));assert.equal(checks,1);
doc.visibilityState='visible';doc.dispatchEvent(new Event('visibilitychange'));assert.equal(checks,2);
stop();clock=900003;events.dispatchEvent(new Event('online'));assert.equal(checks,2);
const stopFailure=watchForAppUpdates({update:async()=>{throw Error('offline');}}, {window:events,document:doc,online:()=>true,now:()=>clock});
clock+=300001;events.dispatchEvent(new Event('online'));await Promise.resolve();stopFailure();
console.log('PASS: update notifications survive pre-login arrival, never auto-reload unsaved work, check on return/online with throttling, and clean up listeners');
