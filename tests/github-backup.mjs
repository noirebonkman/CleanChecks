import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { mkdtemp, mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { encryptBackup, decryptBackup, readBackupKey } from '../tools/github-backup.mjs';

await mkdir('.test-work', { recursive: true });
const directory = await mkdtemp(resolve('.test-work/ci-backup-'));
const key = readBackupKey(randomBytes(32).toString('base64'));
assert.throws(() => readBackupKey('bad-key'));
const original = resolve(directory, 'original.sql'), encrypted = resolve(directory, 'backup.encrypted');
const recovered = resolve(directory, 'recovered.sql');
const sql = Buffer.from('CREATE TABLE example(id TEXT); INSERT INTO example VALUES(\'private-fixture\');\n'.repeat(4000));
await writeFile(original, sql);
await encryptBackup(original, encrypted, key);
assert(!(await readFile(encrypted)).includes(Buffer.from('private-fixture')));
await decryptBackup(encrypted, recovered, key);
assert.deepEqual(await readFile(recovered), sql);
await assert.rejects(() => encryptBackup(original, encrypted, key));
await assert.rejects(() => decryptBackup(encrypted, recovered, key));
assert.deepEqual(await readFile(recovered), sql);
const wrongOutput = resolve(directory, 'wrong.sql');
await assert.rejects(() => decryptBackup(encrypted, wrongOutput, randomBytes(32)));
await assert.rejects(() => stat(wrongOutput));
const damaged = Buffer.from(await readFile(encrypted));
damaged[damaged.length - 18] ^= 1;
const damagedFile = resolve(directory, 'tampered.encrypted');
await writeFile(damagedFile, damaged);
await assert.rejects(() => decryptBackup(damagedFile, wrongOutput, key));
await assert.rejects(() => stat(wrongOutput));
const headerTamper = Buffer.from(await readFile(encrypted));
const timestamp = headerTamper.indexOf(Buffer.from('createdAt')) + 15;
headerTamper[timestamp] = headerTamper[timestamp] === 48 ? 49 : 48;
await writeFile(damagedFile, headerTamper);
await assert.rejects(() => decryptBackup(damagedFile, wrongOutput, key));
console.log('PASS: encrypted CI backup restores exact SQL; wrong key, ciphertext/header tampering and overwrite are rejected without leaving partial SQL');
