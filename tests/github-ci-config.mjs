import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, copyFileSync, writeFileSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
mkdirSync('.test-work', { recursive: true });
const root = mkdtempSync(resolve('.test-work', 'github-ci-'));
mkdirSync(resolve(root, 'tools')); mkdirSync(resolve(root, 'server'));
for (const name of ['ci-cloudflare.mjs', 'github-backup.mjs'])
    copyFileSync('tools/' + name, resolve(root, 'tools', name));
const config = { d1_databases: [{ binding: 'DB', database_name: 'test-db', database_id: '11111111-2222-3333-4444-555555555555' }] };
const file = resolve(root, 'server/wrangler.jsonc');
writeFileSync(file, JSON.stringify(config));
const env = { ...process.env, CLOUDFLARE_API_TOKEN: 'test-only-not-a-token', CLOUDFLARE_ACCOUNT_ID: 'a'.repeat(32), BACKUP_ENCRYPTION_KEY: Buffer.alloc(32, 1).toString('base64') };
const run = (changes = {}) => spawnSync(process.execPath, [resolve(root, 'tools/ci-cloudflare.mjs'), 'check'], { env: { ...env, ...changes }, encoding: 'utf8' });
assert.equal(run().status, 0);
for (const name of ['CLOUDFLARE_API_TOKEN', 'CLOUDFLARE_ACCOUNT_ID', 'BACKUP_ENCRYPTION_KEY']) assert.notEqual(run({ [name]: '' }).status, 0);
config.d1_databases[0].database_id = '00000000-0000-0000-0000-000000000000';
writeFileSync(file, JSON.stringify(config)); assert.notEqual(run().status, 0);
const workflow = readFileSync('.github/workflows/deploy.yml', 'utf8');
assert.match(workflow, /github.ref == 'refs\/heads\/main'/);
assert.match(workflow, /cancel-in-progress: false/);
assert.match(workflow, /contents: read/);
assert.match(workflow, /path: private\/cloudflare-backup.encrypted/);
assert.ok(workflow.indexOf('Retain encrypted backup') < workflow.indexOf('Apply additive database migrations'));
assert.ok(workflow.indexOf('Apply additive database migrations') < workflow.indexOf('Deploy Worker'));
assert.ok(!workflow.split('  deploy:')[0].includes('secrets.'));
assert.ok(!workflow.includes('deploy-pages'));
for (const action of workflow.matchAll(/uses: actions\/[^@]+@([^\s]+)/g)) assert.match(action[1], /^[a-f0-9]{40}$/);
console.log('PASS: missing CI secrets and placeholder DB are blocked; main-only deployment retains encrypted backup before migration');
